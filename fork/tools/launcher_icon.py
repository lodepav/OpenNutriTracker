#!/usr/bin/env python3
"""Writes OpenBite's launcher icon (seam S34) as Android vector drawables.

A diary page with a bite out of its right edge, the page stack showing inside the bite.
Two layers on the 108-unit adaptive canvas: the coloured foreground, where the bite is
painted in the background colour, and the one-colour monochrome layer for themed icons,
where the bite is a real hole (one outline path, even-odd fill).

    python3 fork/tools/launcher_icon.py
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / 'android/app/src/fork/icon/res/drawable'
BG, PAGE, STACK, STACK_LINE, RULE, MARGIN, RING = (
    '#FF1F6F5C', '#FFFBFBF7', '#FFE4ECE8', '#FFC5D5CE', '#FFB9CFC6', '#FFE06B5A', '#FF0F3F33')
SCALE = 0.8
BITE = (80, 55, 12)  # centre and radius; scallops of 0.62 r every 36° around the left half
PAGE_BOX = (31, 25, 48, 60, 5)
STACK_BOX = (34, 27, 46, 60, 5)
RULES = [41, 50, 59, 68, 76]
RINGS = [33, 43, 53, 63, 73]


def rrect(x, y, w, h, r):
    return (f'M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} '
            f'A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} '
            f'V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z')


def circle(cx, cy, r):
    return (f'M{cx - r:.2f},{cy:.2f} A{r:.2f},{r:.2f} 0 1 0 {cx + r:.2f},{cy:.2f} '
            f'A{r:.2f},{r:.2f} 0 1 0 {cx - r:.2f},{cy:.2f} Z')


def scallops(shrink=0.0):
    cx, cy, r = BITE
    return [(cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a)), r * 0.62 - shrink)
            for a in range(180 - 72, 180 + 73, 36)]


def bite_circles(shrink=0.0):
    cx, cy, r = BITE
    return ' '.join([circle(cx, cy, r - shrink)] + [circle(*c) for c in scallops(shrink)])


def bite_outline(shrink=0.0, steps=240):
    """The union of the bite's circles as one polygon, by casting rays from its centre."""
    cx, cy, r = BITE
    points = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        dx, dy = math.cos(t), math.sin(t)
        far = r - shrink
        for sx, sy, sr in scallops(shrink):
            # farthest intersection of the ray with this scallop
            bx, by = cx - sx, cy - sy
            b = bx * dx + by * dy
            disc = b * b - (bx * bx + by * by - sr * sr)
            if disc >= 0:
                far = max(far, -b + math.sqrt(disc))
        points.append((cx + far * dx, cy + far * dy))
    return points


def polygon(points):
    return 'M' + ' L'.join(f'{x:.2f},{y:.2f}' for x, y in points) + ' Z'


def lines(x1, x2, ys):
    return ' '.join(f'M{x1},{y} H{x2}' for y in ys)


def vector(body, comment, size=108):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- [fork] S34 icon: {comment} Generated by fork/tools/launcher_icon.py; edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="108" android:viewportHeight="108">
  <group android:pivotX="54" android:pivotY="54" android:scaleX="{SCALE}" android:scaleY="{SCALE}" android:translateX="1">
{body}
  </group>
</vector>
'''


def fill(d, color, even_odd=False):
    rule = ' android:fillType="evenOdd"' if even_odd else ''
    return f'    <path android:fillColor="{color}"{rule} android:pathData="{d}"/>'


def stroke(d, color, width):
    return (f'    <path android:strokeColor="{color}" android:strokeWidth="{width}" '
            f'android:strokeLineCap="round" android:pathData="{d}"/>')


def page_layers():
    """The page and its stack, whole."""
    return [
        fill(rrect(*STACK_BOX), STACK),
        fill(rrect(*PAGE_BOX), PAGE),
        stroke(lines(41, 71, RULES), RULE, 2),
        stroke('M40,27 V83', MARGIN, 1.6),
        *[fill(rrect(27, y, 9, 4, 2), RING) for y in RINGS],
    ]


def bite_layers():
    """The bite: the stack seen through it, then the hole through everything."""
    stack = rrect(*STACK_BOX)
    return [
        f'    <group>\n      <clip-path android:pathData="{stack}"/>',
        fill(bite_circles(), STACK),
        f'    <group>\n      <clip-path android:pathData="{bite_circles()}"/>',
        stroke(lines(35, 80, range(33, 82, 4)), STACK_LINE, 0.8),
        '    </group>\n    </group>',
        fill(bite_circles(3.2), BG),
    ]


def foreground():
    return '\n'.join(page_layers() + bite_layers())


def monochrome():
    """The page with the bite, the rules and the margin cut out of it; the rings beside it."""
    # clamped to the page's right edge: past it, even-odd would fill the bite in
    right = PAGE_BOX[0] + PAGE_BOX[2]
    outline = [(min(x, right), y) for x, y in bite_outline()]
    holes = []
    for y in RULES:
        # each rule stops short of the bite
        left_of_bite = min((x for x, py in outline if abs(py - y) < 1.5), default=99)
        end = min(71, left_of_bite - 3)
        holes.append(rrect(41, y - 1, end - 41, 2, 1))
    holes.append(rrect(39.2, 27, 1.6, 56, 0.8))
    page = ' '.join([rrect(*PAGE_BOX), polygon(outline), *holes])
    return '\n'.join([
        fill(page, '#FF000000', even_odd=True),
        *[fill(rrect(26, y, 4, 4, 2), '#FF000000') for y in RINGS],
    ])


def splash():
    """Android 12's launch screen: the icon as its mask shows it, a disc, with the page
    still whole; the Flutter splash takes the bite (lib/fork/brand/)."""
    return vector('\n'.join([fill(circle(54, 54, 36 / SCALE), BG)] + page_layers()),
                  "the launch screen's icon, the page before the bite.", size=288)


def svg_path(line):
    """One Android path or clip line as SVG."""
    import re
    attrs = dict(re.findall(r'android:(\w+)="([^"]*)"', line))
    if 'clip-path' in line:
        return None
    out = f'<path d="{attrs["pathData"]}"'
    if 'fillColor' in attrs:
        out += f' fill="#{attrs["fillColor"][3:]}"'
        if attrs.get('fillType') == 'evenOdd':
            out += ' fill-rule="evenodd"'
    else:
        out += (f' fill="none" stroke="#{attrs["strokeColor"][3:]}" '
                f'stroke-width="{attrs["strokeWidth"]}" stroke-linecap="round"')
    return out + '/>'


def svg(layers, disc):
    """The same artwork for Flutter (flutter_svg), clips included."""
    body, clips, depth = [], [], 0
    for layer in layers:
        for line in layer.split('\n'):
            line = line.strip()
            if line.startswith('<clip-path'):
                d = line.split('pathData="')[1].split('"')[0]
                clips.append(f'<clipPath id="c{len(clips)}"><path d="{d}"/></clipPath>')
                body.append(f'<g clip-path="url(#c{len(clips) - 1})">')
            elif line == '</group>':
                body.append('</g>')
            elif line.startswith('<path'):
                body.append(svg_path(line))
    back = f'<circle cx="54" cy="54" r="{36 / SCALE}" fill="#{BG[3:]}"/>' if disc else ''
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">'
            f'<defs>{"".join(clips)}</defs><g transform="translate(55 54) scale({SCALE}) '
            f'translate(-54 -54)">{back}{"".join(body)}</g></svg>\n')


RES.mkdir(parents=True, exist_ok=True)
(RES / 'fork_launcher_foreground.xml').write_text(
    vector(foreground(), "OpenBite's launcher icon, a diary page with a bite out of it."))
(RES / 'fork_launcher_monochrome.xml').write_text(
    vector(monochrome(), 'the one-colour layer Android tints for themed icons.'))
# Android 12's launch screen (upstream's drawable, overridden by name in both themes).
for night in ('', '-night'):
    folder = RES.parent / f'drawable{night}'
    folder.mkdir(exist_ok=True)
    (folder / 'splash_spoon_avd.xml').write_text(splash())
ASSETS = ROOT / 'assets/fork'
ASSETS.mkdir(exist_ok=True)
(ASSETS / 'openbite_page.svg').write_text(svg(page_layers(), disc=True))
(ASSETS / 'openbite_bite.svg').write_text(svg(bite_layers(), disc=False))
