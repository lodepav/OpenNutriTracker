#!/usr/bin/env bash
# The whole test suite in about a fifth of the time: every test file is
# imported into one of a few generated bundles, so the suite compiles a few
# times rather than once a file (most of a plain run is that compiling).
#
#   fork/tools/test-fast.sh            # 4 bundles, run side by side
#   SHARDS=2 fork/tools/test-fast.sh   # fewer, for less memory
#
# Each file's tests run in a group named after it. A bundle shares one
# process, so after each file it closes Hive's boxes and resets the app's
# chosen locale and the service locator, which tests leave behind: left, they
# break later files. The check
# before a merge; plain `flutter test`, a file a process, stays the strict
# one, which fork/tools/verify.sh --strict runs before a release, and for when
# a bundled run fails and you want to know whether a file's own tests do. The bundles (test/_bundle_*.dart) are
# deleted at the end and ignored by git.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
export PATH="$HOME/flutter/bin:$PATH"
cd "$ROOT"

trap 'rm -f test/_bundle_*.dart' EXIT

python3 - "${SHARDS:-4}" <<'EOF'
import os
import sys

shards = int(sys.argv[1])
files = sorted(
    os.path.relpath(os.path.join(d, f), "test")
    for d, _, fs in os.walk("test")
    for f in fs
    if f.endswith("_test.dart")
    # It starts the whole app, whose one-time Hive registration needs a process of its own.
    and f != "upgrade_test.dart"
)
for old in os.listdir("test"):
    if old.startswith("_bundle_"):
        os.remove(os.path.join("test", old))
for n in range(shards):
    mine = files[n::shards]
    lines = ["// Generated by fork/tools/test-fast.sh; not committed.", ""]
    lines += [f"import '{f}' as t{i};" for i, f in enumerate(mine)]
    lines += [
        "import 'package:flutter_test/flutter_test.dart';",
        "import 'package:get_it/get_it.dart';",
        "import 'package:hive_ce/hive.dart';",
        "import 'package:opennutritracker/core/utils/app_locale.dart';",
        "",
        "/// What a file leaves behind in its own process, cleared after it.",
        "Future<void> _isolate() async {",
        "  await Hive.close();",
        "  AppLocale.reset();",
        "  await GetIt.instance.reset();",
        "}",
        "",
        "void main() {",
    ]
    for i, f in enumerate(mine):
        lines += [
            f"  group('{f}', () {{",
            "    tearDownAll(_isolate);",
            f"    t{i}.main();",
            "  });",
        ]
    lines += ["}", ""]
    with open(os.path.join("test", f"_bundle_{n}.dart"), "w") as out:
        out.write("\n".join(lines))
print(f"{len(files)} test files in {shards} bundles")
EOF

# lib/generated is not committed: a pulled ARB change needs it rebuilt.
flutter gen-l10n
fork/tools/heavy.sh flutter test test/_bundle_*.dart test/fork/upgrade/upgrade_test.dart "$@"
