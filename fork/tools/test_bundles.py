# Writes the bundles fork/tools/test-fast.sh runs: every test file imported into one of a few
# test/_bundle_<n>.dart. Files are spread by how long they took in the last run, so the bundles
# finish together; without a last run, they are dealt out in turn.
#   python3 fork/tools/test_bundles.py <shards> [last run's json report]
import json
import os
import sys

# They start the whole app, whose one-time Hive registration needs a process of its own.
ALONE = ("upgrade_test.dart", "day_macro_goals_follow_profile_edit_test.dart",
         "demo_name_test.dart", "demo_per_profile_test.dart", "demo_legacy_mark_test.dart")

# It reports and asserts nothing, and runs wherever the owner's labels are built: an eval to start
# on purpose (fork/tools/verify.sh), not a check.
EVAL = ("macrofactor_search_test.dart",)


def file_times(lines):
    """Seconds per test file in a bundled run's json report, from its tests' names."""
    names, starts, times = {}, {}, {}
    for line in lines:
        try:
            e = json.loads(line)
        except ValueError:
            continue  # a run stopped midway leaves a cut-off last line
        if e.get("type") == "testStart":
            names[e["test"]["id"]] = e["test"]["name"]
            starts[e["test"]["id"]] = e["time"]
        elif e.get("type") == "testDone" and e["testID"] in starts:
            f = names[e["testID"]].split(" ")[0]
            if f.endswith("_test.dart"):
                times[f] = times.get(f, 0) + (e["time"] - starts[e["testID"]]) / 1000
    return times


def split(files, times, shards):
    """The files in [shards] lists, the slowest first into the least-filled one."""
    if not times:
        return [files[n::shards] for n in range(shards)]
    guess = sum(times.values()) / len(times)  # a new file counts as an average one
    bundles = [[] for _ in range(shards)]
    load = [0.0] * shards
    for f in sorted(files, key=lambda f: (-times.get(f, guess), f)):
        n = load.index(min(load))
        bundles[n].append(f)
        load[n] += times.get(f, guess)
    return [sorted(b) for b in bundles]


def bundle_source(mine):
    lines = ["// Generated by fork/tools/test-fast.sh; not committed.", ""]
    lines += [f"import '{f}' as t{i};" for i, f in enumerate(mine)]
    lines += [
        "import 'package:flutter_test/flutter_test.dart';",
        "import 'package:get_it/get_it.dart';",
        "import 'package:hive_ce/hive.dart';",
        "import 'package:opennutritracker/core/utils/app_locale.dart';",
        "",
        "/// What a file leaves behind in its own process, cleared after it.",
        "Future<void> _isolate() async {",
        "  await Hive.close();",
        "  AppLocale.reset();",
        "  await GetIt.instance.reset();",
        "}",
        "",
        "void main() {",
    ]
    for i, f in enumerate(mine):
        lines += [
            f"  group('{f}', () {{",
            "    tearDownAll(_isolate);",
            f"    t{i}.main();",
            "  });",
        ]
    lines += ["}", ""]
    return "\n".join(lines)


def main(shards, report):
    files = sorted(
        os.path.relpath(os.path.join(d, f), "test")
        for d, _, fs in os.walk("test")
        for f in fs
        if f.endswith("_test.dart") and f not in ALONE and f not in EVAL
    )
    times = {}
    if report and os.path.exists(report):
        with open(report) as r:
            times = file_times(r)
    for old in os.listdir("test"):
        if old.startswith("_bundle_"):
            os.remove(os.path.join("test", old))
    for n, mine in enumerate(split(files, times, shards)):
        with open(os.path.join("test", f"_bundle_{n}.dart"), "w") as out:
            out.write(bundle_source(mine))
    how = "by the last run's times" if times else "in turn"
    print(f"{len(files)} test files in {shards} bundles, spread {how}")


if __name__ == "__main__":
    main(int(sys.argv[1]), sys.argv[2] if len(sys.argv) > 2 else None)
